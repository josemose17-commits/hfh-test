// Derive purchase families from Umalator's Global game-data metadata.
// Usage: node tools/build_skill_purchases.js <Global meta> <Global data> [<JP meta> <JP data>]
// No Umalator implementation is copied; output contains game-data facts only.
const fs = require("node:fs");
const path = require("node:path");
const [metaFile, dataFile, jpMetaFile, jpDataFile] = process.argv.slice(2);
// Preserve Global facts when both snapshots contain the same skill.
const meta = Object.assign({}, jpMetaFile ? JSON.parse(fs.readFileSync(jpMetaFile, "utf8")) : {}, JSON.parse(fs.readFileSync(metaFile, "utf8")));
const data = Object.assign({}, jpDataFile ? JSON.parse(fs.readFileSync(jpDataFile, "utf8")) : {}, JSON.parse(fs.readFileSync(dataFile, "utf8")));
const groups = new Map();
Object.keys(meta).forEach((id) => {
  const m = meta[id], d = data[id];
  // Negative, unique and evolved skills are outside this purchase model.
  if (!d || ![1, 2].includes(d.rarity) || String(m.iconId).endsWith("4")) return;
  if (!groups.has(m.groupId)) groups.set(m.groupId, []);
  groups.get(m.groupId).push(id);
});
const skills = {};
for (const [group, ids] of groups) {
  // The white tiers precede gold. Within white tiers, ○ precedes ◎.
  ids.sort((a, b) => data[a].rarity - data[b].rarity || +b - +a);
  if (ids.filter((id) => data[id].rarity === 2).length > 1) throw new Error("Ambiguous gold family " + group);
  ids.forEach((id, i) => { skills[id] = [group, meta[id].baseCost, i ? ids[i - 1] : null, data[id].rarity]; });
}
const result = {
  meta: { source: "Umalator Global and JP game-data metadata; Global takes precedence; game data © Cygames, Inc.",
    urls: ["https://github.com/alpha123/uma-tools/tree/master/umalator-global", "https://github.com/alpha123/uma-tools/blob/master/skill_meta.json", "https://github.com/alpha123/uma-skill-tools/blob/master/data/skill_data.json"], built: new Date().toISOString().slice(0, 10),
    fields: ["family", "incremental SP cost", "prerequisite", "rarity"], scope: "Normal/gold/inherited skills; evolved and negative skills excluded" }, skills,
  negative: Object.keys(meta).filter((id) => String(meta[id].iconId).endsWith("4"))
};
const output = "// Generated by tools/build_skill_purchases.js. Game data © Cygames, Inc.\n" +
  "(function (root) {\n  const data = " + JSON.stringify(result) + ";\n" +
  "  if (typeof module !== \"undefined\" && module.exports) module.exports = data;\n  else root.UmaSkillPurchases = data;\n})(typeof window !== \"undefined\" ? window : globalThis);\n";
fs.writeFileSync(path.join(__dirname, "../data/skill-purchases.js"), output);
console.log("Wrote verified purchase metadata for", Object.keys(skills).length, "skills");
